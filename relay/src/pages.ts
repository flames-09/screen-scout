function page(title: string, body: string): Response {
  return new Response(
    `<!doctype html><html lang="en"><head><meta charset="utf-8">
     <meta name="viewport" content="width=device-width,initial-scale=1">
     <title>${title} — Screen Scout relay</title><style>${STYLE}</style></head>
     <body><main>${body}<footer>Screen Scout relay · <a href="/privacy">Privacy</a> · <a href="/terms">Terms</a></footer></main></body></html>`,
    { headers: { 'Content-Type': 'text/html; charset=utf-8', 'Cache-Control': 'public, max-age=300' } }
  )
}

export function landingPage(): Response {
  return page(
    'Screen Scout relay',
    `<h1>Screen Scout relay</h1>
     <p>This is the small forwarding service that lets Screen Scout work without every user
        bringing their own API key. It accepts one screenshot question at a time, enforces a
        free daily limit per device, and streams the answer back.</p>
     <h2>What it does with your data</h2>
     <ul>
       <li>Questions that include a screenshot are forwarded to Cloudflare Workers AI
           (Llama 4 Scout) to generate the answer; text-only questions may be served
           by Groq.</li>
       <li>The relay does not store screenshots, questions, or answers.</li>
       <li>It stores only a random device id and daily usage counters.</li>
     </ul>
     <p>Full detail: <a href="/privacy">privacy</a> and <a href="/terms">terms</a>.</p>`
  )
}

export function privacyPage(): Response {
  return page(
    'Privacy',
    `<h1>Privacy</h1>
     <p>Screen Scout is designed so that nothing leaves your computer until you press <strong>Send</strong>.
        When you use the free hosted mode, this relay forwards your selected screenshot crop and your
        question to a model provider and streams the answer back.</p>
     <h2>What is processed</h2>
     <ul>
       <li><strong>Screenshot + question</strong> — forwarded to Cloudflare Workers AI
           (Llama 4 Scout). The relay does not write them to storage and does not log
           their contents.</li>
       <li><strong>Text-only questions</strong> — questions sent without a screenshot may
           be served by Groq instead.</li>
       <li><strong>Device id</strong> — a random identifier generated by the app. It is not tied to your
           name, email, or account, and is used only for rate limiting.</li>
       <li><strong>Counters</strong> — how many questions a device asked today and in the current
           5-hour window. Usage counters are deleted after at most 7 days; an idle device id is
           deleted after 30 days.</li>
     </ul>
     <h2>What is not collected</h2>
     <p>No accounts, no email addresses, no IP addresses stored beyond short-lived abuse throttling,
        no analytics, no advertising identifiers, and no conversation history.</p>
     <h2>Providers</h2>
     <p>Cloudflare states that Workers AI does not use customer inputs to train models.
        Groq's services agreement prohibits using API inputs and outputs to train or
        fine-tune models, and Groq does not retain inference data by default.</p>
     <h2>Your choice</h2>
     <p>You can switch to <strong>My own NVIDIA key</strong> in Settings at any time. In that mode the app
        talks directly to the endpoint you configure and this relay is never contacted.</p>
     <p>Questions: open an issue on the project repository.</p>`
  )
}

